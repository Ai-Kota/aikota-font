SHAPE_DEFAULT = [(0.0, 1.0), (1.0, 1.0)]

def shape_for(stk, style='KAISO'):
    """按风格取笔画 taper 曲线."""
    return SHAPE.get(style, SHAPE['KAISO']).get(stk, SHAPE_DEFAULT)

def set_style(style):
    """切换全局笔形风格 (KAISO/SHOULJIN/YUAN/ART)."""
    global _STYLE
    _STYLE = style
    return _STYLE

_STYLE = 'KAISO'

def _interp_shape(shape_pts, t):
    """t in [0,1] -> 相对半宽. 线性插值."""
    if t <= shape_pts[0][0]:
        return shape_pts[0][1]
    if t >= shape_pts[-1][0]:
        return shape_pts[-1][1]
    for i in range(len(shape_pts) - 1):
        (t0, w0), (t1, w1) = shape_pts[i], shape_pts[i + 1]
        if t0 <= t <= t1:
            f = (t - t0) / (t1 - t0) if t1 > t0 else 0
            return w0 + (w1 - w0) * f
    return shape_pts[-1][1]

def brush_contour(stroke, n_samples=6, style=None):
    """一条笔画 -> 多边形轮廓 (闭合). 输入 (stk, x, y, dx, dy, w) 字形坐标.
    style: KAISO/SHOULJIN/YUAN/ART (None=当前全局风格).
    返回 [(x,y)...] 闭合多边形 (上轮廓 + 下轮廓 拼接)."""
    stk, x, y, dx, dy, w = stroke
    x0, y0 = x, y
    x1, y1 = x + dx, y + dy
    L = math.hypot(dx, dy) or 1.0
    ux, uy = dx / L, dy / L
    nx, ny = -uy, ux
    hw = w / 2.0
    shape = shape_for(stk, style if style else _STYLE)
    pts = []
    for i in range(n_samples + 1):
        t = i / n_samples
        cx = x0 + ux * L * t
        cy = y0 + uy * L * t
        r = _interp_shape(shape, t) * hw
        # 上侧 / 下侧
        pts.append((cx + nx * r, cy + ny * r))   # 上轮廓
    # 上轮廓 -> 下轮廓 (倒序)
    for i in range(n_samples + 1):
        t = 1.0 - i / n_samples
        cx = x0 + ux * L * t
        cy = y0 + uy * L * t
        r = _interp_shape(shape, t) * hw
        pts.append((cx - nx * r, cy - ny * r))   # 下轮廓
    return pts

def all_contours(strokes_scaled, n_samples=6, style=None):
    """所有笔画 (scale_strokes 输出) -> 轮廓列表."""
    return [brush_contour(s, n_samples, style) for s in strokes_scaled]

