# 每部件: name -> list[(type, x, y, dx, dy, w)]
# 约定: 部件格 1000x1000, 笔画坐标在 60..940 范围内, 基准宽 70

# 坐标系定死 (对照 A 路线 ground-truth 验证过):
#   数据源 medians 是 font y-up (py 小=画面下/底, py 大=画面上/顶).
#   但 layout.scale_strokes 期望输入是 y-down 局部系 (py 小=顶, py 大=底),
#   因为它做 字形y=y0+(1000-py)*sy, 字形dy=-dy*sy.
#   所以 medians 坐标要用 _mirror(): py→1000-py, dy→-dy. 已应用.
# 宽度分档: 横~100 / 竖~70 / 撇捺~60-65 / 点~55. 笔画类型见文件头.
def _mirror(strokes):
    """把 font y-up 的 medians 笔画转成 scale_strokes 期望的 y-down 局部系."""
    return [(t, x, 1000 - y, dx, -dy, w) for (t, x, y, dx, dy, w) in strokes]

